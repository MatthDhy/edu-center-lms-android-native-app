-- V1: schema đã chỉnh từ LMS_App.sql (BIGINT, TIMESTAMP, CHECK, bảng còn thiếu)
-- Các phần mới so với bản cũ được đánh dấu [NEW]/[FIX]

CREATE TABLE users (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name            VARCHAR(100) NOT NULL,
  email                VARCHAR(100) NOT NULL UNIQUE,
  password_hash        VARCHAR(255) NOT NULL,                 -- [FIX] đổi tên từ "password"
  phone                VARCHAR(15),
  avatar_url           VARCHAR(500),                          -- [NEW]
  role                 VARCHAR(20)  NOT NULL CHECK (role IN ('STUDENT','TEACHER','ADMIN')),
  status               VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','LOCKED')),
  must_change_password BOOLEAN      NOT NULL DEFAULT TRUE,    -- [NEW] đổi mật khẩu lần đầu
  created_at           TIMESTAMP    NOT NULL DEFAULT NOW()
);

-- "courses" = một LỚP HỌC cụ thể (Toán 11A) có 1 giảng viên. Bỏ join_code vì không có tự đăng ký.
CREATE TABLE courses (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id     BIGINT NOT NULL REFERENCES users(id),
  course_name    VARCHAR(150) NOT NULL,
  description    TEXT,
  tuition_fee    NUMERIC(12,2) NOT NULL DEFAULT 0,            -- [NEW] học phí/khóa
  total_sessions INT,                                         -- [NEW] tổng số buổi (36)
  status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at     TIMESTAMP NOT NULL DEFAULT NOW()
);

-- [NEW] Từng buổi học: nguồn dữ liệu cho "ca học kế tiếp", lịch, điểm danh, lương
CREATE TABLE lessons (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  room       VARCHAR(50),
  topic      VARCHAR(200),
  start_time TIMESTAMP NOT NULL,
  end_time   TIMESTAMP NOT NULL,
  status     VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','DONE','CANCELED'))
);
CREATE INDEX idx_lessons_course_time ON lessons(course_id, start_time);

CREATE TABLE enrollments (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  student_id BIGINT NOT NULL REFERENCES users(id),
  status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  joined_at  TIMESTAMP NOT NULL DEFAULT NOW(),
  UNIQUE (course_id, student_id)
);
CREATE INDEX idx_enrollments_student ON enrollments(student_id);

CREATE TABLE materials (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id   BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  lesson_id   BIGINT REFERENCES lessons(id) ON DELETE SET NULL,   -- [NEW]
  uploaded_by BIGINT REFERENCES users(id),                         -- [NEW]
  title       VARCHAR(200) NOT NULL,
  description TEXT,
  file_url    VARCHAR(500),
  created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE assignments (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id      BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  title          VARCHAR(200) NOT NULL,
  description    TEXT,
  attachment_url VARCHAR(500),
  deadline       TIMESTAMP,
  max_score      NUMERIC(5,2) NOT NULL DEFAULT 10,                 -- [NEW]
  created_at     TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE submissions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id    BIGINT NOT NULL REFERENCES users(id),
  file_url      VARCHAR(500),
  submitted_at  TIMESTAMP NOT NULL DEFAULT NOW(),
  is_late       BOOLEAN NOT NULL DEFAULT FALSE,                    -- [NEW]
  score         NUMERIC(5,2),
  feedback      TEXT,
  graded_at     TIMESTAMP,                                         -- [NEW]
  UNIQUE (assignment_id, student_id)
);

CREATE TABLE quizzes (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id        BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  title            VARCHAR(200) NOT NULL,
  description      TEXT,
  duration_minutes INT,
  start_time       TIMESTAMP,
  end_time         TIMESTAMP,
  is_published     BOOLEAN NOT NULL DEFAULT FALSE,                 -- [NEW] Preview -> Xuất bản
  created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE questions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id     BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  content     TEXT NOT NULL,
  explanation TEXT,                                                -- [NEW] cột explanation của file Excel
  order_index INT NOT NULL DEFAULT 0                               -- [NEW]
);

CREATE TABLE question_options (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  content     VARCHAR(500) NOT NULL,
  is_correct  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE quiz_attempts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id      BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  student_id   BIGINT NOT NULL REFERENCES users(id),
  score        NUMERIC(5,2),
  started_at   TIMESTAMP NOT NULL DEFAULT NOW(),
  submitted_at TIMESTAMP,
  UNIQUE (quiz_id, student_id)
);

CREATE TABLE student_answers (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id         BIGINT NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
  question_id        BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  selected_option_id BIGINT REFERENCES question_options(id),
  UNIQUE (attempt_id, question_id)
);

CREATE TABLE notifications (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      VARCHAR(200) NOT NULL,
  content    TEXT,
  is_read    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_notifications_user ON notifications(user_id, is_read);

-- [NEW] Push FCM cần biết token của từng thiết bị
CREATE TABLE device_tokens (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  fcm_token  VARCHAR(500) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE attendance_sessions (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  lesson_id  BIGINT REFERENCES lessons(id) ON DELETE SET NULL,     -- [NEW]
  created_by BIGINT NOT NULL REFERENCES users(id),                  -- [NEW]
  pin_code   VARCHAR(6) NOT NULL,                                   -- [NEW] PIN dự phòng
  qr_token   VARCHAR(100) NOT NULL UNIQUE,                          -- [FIX] thay qr_code
  start_time TIMESTAMP NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMP NOT NULL,                                    -- [FIX] thay end_time
  created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE attendance_records (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id    BIGINT NOT NULL REFERENCES attendance_sessions(id) ON DELETE CASCADE,
  student_id    BIGINT NOT NULL REFERENCES users(id),
  check_in_time TIMESTAMP NOT NULL DEFAULT NOW(),
  status        VARCHAR(20) NOT NULL DEFAULT 'PRESENT' CHECK (status IN ('PRESENT','LATE','EXCUSED','ABSENT')),
  method        VARCHAR(10) NOT NULL DEFAULT 'QR' CHECK (method IN ('QR','PIN','MANUAL')),  -- [NEW]
  UNIQUE (session_id, student_id)
);

-- [NEW] Đơn xin nghỉ & học bù
CREATE TABLE leave_requests (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       BIGINT NOT NULL REFERENCES users(id),
  lesson_id        BIGINT NOT NULL REFERENCES lessons(id),
  makeup_lesson_id BIGINT REFERENCES lessons(id),
  reason           TEXT NOT NULL,
  status           VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  reject_reason    TEXT,
  reviewed_by      BIGINT REFERENCES users(id),
  created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

-- [NEW] Tách "khoản phải đóng" (bill) và "giao dịch đã trả" (payment)
CREATE TABLE tuition_bills (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       BIGINT NOT NULL REFERENCES users(id),
  course_id        BIGINT NOT NULL REFERENCES courses(id),
  title            VARCHAR(200) NOT NULL,                           -- "Đợt 1"
  amount           NUMERIC(12,2) NOT NULL,
  due_date         DATE,
  status           VARCHAR(20) NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID','PAID','OVERDUE')),
  transfer_content VARCHAR(100) NOT NULL UNIQUE,                    -- nội dung CK để đối soát webhook
  created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE tuition_payments (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_id      BIGINT NOT NULL REFERENCES tuition_bills(id),
  amount       NUMERIC(12,2) NOT NULL,
  method       VARCHAR(20) NOT NULL CHECK (method IN ('VIETQR','CASH')),
  bank_txn_id  VARCHAR(100) UNIQUE,                                 -- chống xử lý webhook 2 lần
  confirmed_by BIGINT REFERENCES users(id),
  paid_at      TIMESTAMP NOT NULL DEFAULT NOW(),
  created_at   TIMESTAMP NOT NULL DEFAULT NOW()
);

