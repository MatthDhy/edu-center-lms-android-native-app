-- V2: Quên mật khẩu bằng OTP (Android: ForgotPassword -> Otp -> ResetPassword)
-- OTP 6 số lưu dạng BCrypt hash. Sau khi verify đúng, server cấp reset token (lưu SHA-256) để đặt mật khẩu mới.
CREATE TABLE password_reset_otps (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  otp_hash         VARCHAR(100) NOT NULL,
  attempts         INT NOT NULL DEFAULT 0,          -- số lần nhập sai OTP (tối đa 5)
  expires_at       TIMESTAMP NOT NULL,
  reset_token_hash VARCHAR(64),                      -- SHA-256 hex của reset token (sau verify)
  verified_at      TIMESTAMP,
  used_at          TIMESTAMP,                        -- đã dùng / bị vô hiệu hóa
  created_at       TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_pwd_reset_user  ON password_reset_otps(user_id, id DESC);
CREATE INDEX idx_pwd_reset_token ON password_reset_otps(reset_token_hash);
