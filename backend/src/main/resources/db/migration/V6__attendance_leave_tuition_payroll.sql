CREATE TABLE teacher_rates (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  hourly_rate    NUMERIC(12,2) NOT NULL CHECK (hourly_rate >= 0),
  effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at     TIMESTAMP NOT NULL DEFAULT NOW(),
  UNIQUE (teacher_id, effective_from)
);

CREATE TABLE payroll_periods (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month       VARCHAR(7) NOT NULL UNIQUE,                       -- 'YYYY-MM'
  status      VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','APPROVED')),
  approved_at TIMESTAMP,
  created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE payroll_items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id   BIGINT NOT NULL REFERENCES payroll_periods(id) ON DELETE CASCADE,
  teacher_id  BIGINT NOT NULL REFERENCES users(id),
  lesson_id   BIGINT REFERENCES lessons(id) ON DELETE SET NULL,
  description VARCHAR(300) NOT NULL,
  work_date   DATE,
  hours       NUMERIC(6,2) NOT NULL,
  rate        NUMERIC(12,2) NOT NULL,
  amount      NUMERIC(14,2) NOT NULL
);
CREATE INDEX idx_payroll_items_period ON payroll_items(period_id, teacher_id);

CREATE INDEX idx_att_sessions_course_time ON attendance_sessions(course_id, start_time);
CREATE INDEX idx_att_sessions_pin ON attendance_sessions(pin_code, expires_at);
CREATE INDEX idx_att_records_student ON attendance_records(student_id);
CREATE INDEX idx_leave_student ON leave_requests(student_id, status);
CREATE INDEX idx_leave_lesson ON leave_requests(lesson_id);
CREATE INDEX idx_bills_course_status ON tuition_bills(course_id, status);
CREATE INDEX idx_bills_student ON tuition_bills(student_id);
CREATE INDEX idx_payments_bill ON tuition_payments(bill_id);
CREATE INDEX idx_payments_paid_at ON tuition_payments(paid_at);

